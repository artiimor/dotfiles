-- Environmental variables (for reference https://wiki.hypr.land/Configuring/Advanced-and-Cool/Environment-variables/)
-- if you use UWSM, define your variables in ~/.config/uwsm/env
-- if you don't use UWSM, define your variables here (e.g. hl.env("QT_QPA_PLATFORM", "wayland"))

-- The variables live only in ~/.config/uwsm/env (which only the uwsm session reads):
-- its `export K=V` lines are read here so the plain "Hyprland" session without uwsm matches.
-- With uwsm nothing changes: same values. If the file is missing, nothing is set.
-- $VAR is expanded with the environment Hyprland started with (only what the env file uses: PATH, HOME).
-- env.d/gpu is generated by install.sh depending on the GPU (NVIDIA variables); uwsm reads it too.
local function parse(line)
	local k, v = line:match("^%s*export%s+([%a_][%w_]*)=(.*)$")
	if not k then return nil end
	local q = v:sub(1, 1)
	if q == '"' or q == "'" then
		v = v:match("^" .. q .. "(.-)" .. q) or v:sub(2)
	else
		v = v:gsub("%s+#.*$", ""):gsub("%s+$", "")
	end
	-- $VAR / ${VAR} as the shell does (e.g. PATH="$HOME/...:$PATH"), except inside '...'
	if q ~= "'" then
		v = v:gsub("%$({?)([%a_][%w_]*)}?", function(_, name) return os.getenv(name) or "" end)
	end
	return k, v
end

for _, name in ipairs({ "env", "env.d/gpu" }) do
	local f = io.open(os.getenv("HOME") .. "/.config/uwsm/" .. name)
	if f then
		for line in f:lines() do
			local ok, k, v = pcall(parse, line)
			if ok and k then hl.env(k, v) end
		end
		f:close()
	end
end
